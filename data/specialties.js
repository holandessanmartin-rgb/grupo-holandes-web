function getSpecialtyById(id) {
  return SPECIALTIES.find(s => s.id === id);
}

function getAllActiveSpecialties() {
  return SPECIALTIES.filter(s => s.activo).sort((a, b) => a.orden - b.orden);
}

function getSpecialtiesForCampus(campusId) {
  return getAllActiveSpecialties().filter(s => s.campuses.includes(campusId));
}

function getSpecialtySEO(specialtyId) {
  const specialty = getSpecialtyById(specialtyId);
  return specialty ? specialty.seo : null;
}

